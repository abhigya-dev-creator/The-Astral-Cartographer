import React, { useState } from 'react';
import { X, Download, Copy, Check, FileText } from 'lucide-react';
import type { AnalysisDetails, RepositorySummary } from '../../lib/api';
import type { HealthScoreResult, RecommendationItem, SeverityCategoryInfo, SeverityLevel } from './healthTypes';

interface FullReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  selectedRepo: RepositorySummary | null;
  analysis: AnalysisDetails | null;
  scoreResult: HealthScoreResult;
  categories: Record<SeverityLevel, SeverityCategoryInfo>;
  recommendations: RecommendationItem[];
}

export function FullReportModal({
  isOpen,
  onClose,
  selectedRepo,
  analysis,
  scoreResult,
  categories,
  recommendations,
}: FullReportModalProps) {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const repoName = selectedRepo ? `${selectedRepo.owner}/${selectedRepo.name}` : 'Unknown Repository';
  const metrics = analysis?.metrics;

  // Build markdown content
  const reportMarkdown = `# Architectural Health Report: ${repoName}
Generated on: ${new Date().toISOString()}

## 1. Overall Health Score
- **Score:** ${scoreResult.score !== null ? `${scoreResult.score}/100` : 'Unavailable'}
- **Category:** ${scoreResult.categoryLabel}
- **Status:** ${scoreResult.headline}
- **Summary:** ${scoreResult.explanation}
${scoreResult.coverageNotice ? `- **Coverage Note:** ${scoreResult.coverageNotice}\n` : ''}
### Factor Breakdown
- Healthy Files: ${scoreResult.breakdown.healthyPercent}%
- Needs Attention: ${scoreResult.breakdown.needsAttentionPercent}%
- Critical Issues: ${scoreResult.breakdown.criticalPercent}%

${
  scoreResult.deductions.length > 0
    ? `### Scoring Deductions
${scoreResult.deductions.map((d) => `- **${d.label}:** -${d.points} pts`).join('\n')}`
    : ''
}

## 2. Key Repository Metrics
- **Total Discovered Files:** ${metrics?.totalFiles?.toLocaleString() ?? 'N/A'}
- **Analyzed Source Modules:** ${metrics?.coverage?.analyzedCodeFiles?.toLocaleString() ?? 'N/A'}
- **Total Functions:** ${metrics?.functions?.toLocaleString() ?? 'N/A'}
- **Dependency Connections:** ${metrics?.dependencies?.toLocaleString() ?? 'N/A'}
- **External Packages:** ${metrics?.dependencyMetrics?.externalPackages?.toLocaleString() ?? 'N/A'}

## 3. Issues Summary by Severity
- **Critical:** ${categories.critical.count}
- **High:** ${categories.high.count}
- **Medium:** ${categories.medium.count}
- **Low:** ${categories.low.count}
- **Total Architectural Findings:** ${
    categories.critical.count + categories.high.count + categories.medium.count + categories.low.count
  }

## 4. Architectural Recommendations & Action Plan
${recommendations
  .map(
    (r, idx) => `### ${idx + 1}. ${r.title}
- **Assessment:** ${r.subtitle}
- **Why It Matters:** ${r.whyItMatters}
- **Confidence:** ${r.confidence}
- **Evidence:**
${r.evidence.map((e) => `  - ${e}`).join('\n')}
- **Affected Modules:**
${r.supportingFiles.map((sf) => `  - \`${sf.path}${sf.line ? `:${sf.line}` : ''}\``).join('\n')}
- **Recommended Next Steps:**
${r.nextSteps.map((s) => `  - ${s}`).join('\n')}
`
  )
  .join('\n')}

---
*Report generated by The Astral Cartographer Architectural Health Engine.*
`;

  const handleCopy = () => {
    navigator.clipboard.writeText(reportMarkdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([reportMarkdown], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `architectural-health-${selectedRepo?.name || 'repo'}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="health-modal-overlay" onClick={onClose} role="dialog" aria-modal="true">
      <div className="health-modal-content" style={{ maxWidth: 820 }} onClick={(e) => e.stopPropagation()}>
        <div className="health-modal-header">
          <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
            <FileText size={20} color="#38BDF8" />
            <h2 className="health-modal-title">Architectural Health Full Report</h2>
          </div>
          <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
            <button
              type="button"
              className="health-modal-open-code-btn"
              onClick={handleCopy}
              title="Copy markdown to clipboard"
            >
              {copied ? <Check size={14} color="#43D9A3" /> : <Copy size={14} />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              type="button"
              className="health-modal-open-code-btn"
              onClick={handleDownload}
              title="Download report as markdown"
            >
              <Download size={14} />
              <span>Download .md</span>
            </button>
            <button
              type="button"
              className="health-modal-close-btn"
              onClick={onClose}
              aria-label="Close dialog"
            >
              <X size={20} />
            </button>
          </div>
        </div>

        <div className="health-modal-list" style={{ padding: 24 }}>
          <pre
            style={{
              background: 'rgba(8, 14, 30, 0.85)',
              padding: 20,
              borderRadius: 10,
              border: '1px solid rgba(135, 155, 255, 0.15)',
              color: 'var(--color-text)',
              fontSize: 12,
              fontFamily: 'var(--font-mono)',
              lineHeight: 1.6,
              overflowX: 'auto',
              whiteSpace: 'pre-wrap',
              margin: 0,
            }}
          >
            {reportMarkdown}
          </pre>
        </div>
      </div>
    </div>
  );
}
